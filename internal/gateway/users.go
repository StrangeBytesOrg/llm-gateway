package gateway

import (
	"strings"
	"time"
)

type User struct {
	Alias            string `json:"alias"`
	ModelAccessGroup string `json:"model_access_group"`
	ID               string `json:"id" doc:"Immutable user ID, supplied at creation or generated by the gateway when omitted."`
	Enabled          bool   `json:"enabled"`
	PolicyID         string `json:"budget_policy_id"`
	AllowanceID      string `json:"budget_allowance_id"`
	Budget           int64  `json:"-"`
	BudgetUSD        string `json:"budget_usd"`
	Cadence          string `json:"cadence"`
	Anchor           int64  `json:"anchor_unix"`
	Created          int64  `json:"created_unix"`
}

func validUserID(id string) bool {
	return strings.TrimSpace(id) != "" && len(id) <= 256
}

func newUser(id string, budget int64, cadence string, anchor time.Time, group, alias string) User {
	if id == "" {
		id = ID("usr_")
	}
	return User{
		AllowanceID:      ID("allow_"),
		PolicyID:         ID("pol_"),
		ModelAccessGroup: group,
		ID:               id,
		Enabled:          true,
		Budget:           budget,
		BudgetUSD:        FormatUSD(budget),
		Cadence:          cadence,
		Anchor:           anchor.Unix(),
		Created:          time.Now().Unix(),
		Alias:            alias,
	}
}
