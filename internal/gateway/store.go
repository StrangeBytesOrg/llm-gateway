const schemaVersion = 1

var (
	ErrUnauthorized  = errors.New("invalid_api_key")
	ErrDisabled      = errors.New("user_disabled")
	ErrBudget        = errors.New("budget_exhausted")
	ErrNotStarted    = errors.New("budget_not_started")
	ErrInvalidUserID = errors.New("invalid_user_id")
	ErrConflict      = errors.New("conflict")
	ErrNotFound      = errors.New("not_found")
)

type Store struct {
	db   *sql.DB
	lock *os.File
	path string
}

func OpenStore(path string) (*Store, error) {
	abs, err := filepath.Abs(path)
	if err != nil {
		return nil, err
	}
	if err = os.MkdirAll(filepath.Dir(abs), 0700); err != nil {
		return nil, err
	}
	lock, err := os.OpenFile(abs+".lock", os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return nil, err
	}
	if err = unix.Flock(int(lock.Fd()), unix.LOCK_EX|unix.LOCK_NB); err != nil {
		lock.Close()
		return nil, fmt.Errorf("database already owned by another gateway: %w", err)
	}
	fail := func(e error) (*Store, error) { lock.Close(); return nil, e }
	f, err := os.OpenFile(abs, os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return fail(err)
	}
	f.Close()
	u := url.URL{Scheme: "file", Path: abs}
	q := u.Query()
	q.Add("_pragma", "journal_mode(WAL)")
	q.Add("_pragma", "synchronous(FULL)")
	q.Add("_pragma", "foreign_keys(1)")
	q.Add("_pragma", "busy_timeout(5000)")
	u.RawQuery = q.Encode()
	db, err := sql.Open("sqlite", u.String())
	if err != nil {
		return fail(err)
	}
	db.SetMaxOpenConns(1)
	db.SetMaxIdleConns(1)
	s := &Store{db: db, lock: lock, path: abs}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if err = s.migrate(ctx); err != nil {
		s.Close()
		return nil, err
	}
	return s, nil
}

func (s *Store) Close() error {
	err := s.db.Close()
	e := s.lock.Close()
	if err != nil {
		return err
	}
	return e
}
func (s *Store) Ping(ctx context.Context) error { return s.db.PingContext(ctx) }
func (s *Store) migrate(ctx context.Context) error {
	var version int
	if err := s.db.QueryRowContext(ctx, "PRAGMA user_version").Scan(&version); err != nil {
		return err
	}
	if version > schemaVersion {
		return errors.New("database schema is newer than this binary")
	}
	if version == schemaVersion {
		return nil
	}
	schema, err := migrations.ReadFile("migrations/001_init.sql")
	if err != nil {
		return err
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, string(schema)); err != nil {
		return err
	}
	if _, err = tx.ExecContext(ctx, fmt.Sprintf("PRAGMA user_version=%d", schemaVersion)); err != nil {
		return err
	}
	return tx.Commit()
}

func ID(prefix string) string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return prefix + hex.EncodeToString(b)
}
func keyHash(key string) string { h := sha256.Sum256([]byte(key)); return hex.EncodeToString(h[:]) }

type User struct {
	ID        string `json:"id" doc:"Immutable user ID, supplied at creation or generated by the gateway when omitted."`
	Enabled   bool   `json:"enabled"`
	Budget    int64  `json:"-"`
	BudgetUSD string `json:"budget_usd"`
	Cadence   string `json:"cadence"`
	Anchor    int64  `json:"anchor_unix"`
	Created   int64  `json:"created_unix"`
}

type scanner interface{ Scan(...any) error }

func scanUser(row scanner) (User, error) {
	var u User
	err := row.Scan(&u.ID, &u.Enabled, &u.Budget, &u.Cadence, &u.Anchor, &u.Created)
	u.BudgetUSD = FormatUSD(u.Budget)
	return u, err
}

const userCols = "id,enabled,budget,cadence,anchor,created"

func audit(ctx context.Context, tx *sql.Tx, action, target string, detail any) error {
	b, err := json.Marshal(detail)
	if err != nil {
		return err
	}
	_, err = tx.ExecContext(ctx, "INSERT INTO audit(action,target,detail,created) VALUES(?,?,?,?)", action, target, string(b), time.Now().Unix())
	return err
}

func (s *Store) CreateUser(ctx context.Context, id string, budget int64, cadence string, anchor time.Time) (User, error) {
	if id == "" {
		id = ID("usr_")
	}
	if strings.TrimSpace(id) == "" || len(id) > 256 {
		return User{}, ErrInvalidUserID
	}
	u := User{ID: id, Enabled: true, Budget: budget, BudgetUSD: FormatUSD(budget), Cadence: cadence, Anchor: anchor.Unix(), Created: time.Now().Unix()}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return u, err
	}
	defer tx.Rollback()
	var exists int
	if err = tx.QueryRowContext(ctx, "SELECT count(*) FROM users WHERE id=?", id).Scan(&exists); err != nil {
		return u, err
	}
	if exists != 0 {
		return u, ErrConflict
	}
	_, err = tx.ExecContext(ctx, "INSERT INTO users("+userCols+") VALUES(?,?,?,?,?,?)", u.ID, u.Enabled, u.Budget, u.Cadence, u.Anchor, u.Created)
	if err != nil {
		return u, err
	}
	if err = audit(ctx, tx, "user.create", u.ID, u); err != nil {
		return u, err
	}
	return u, tx.Commit()
}

func (s *Store) User(ctx context.Context, id string) (User, error) {
	u, err := scanUser(s.db.QueryRowContext(ctx, "SELECT "+userCols+" FROM users WHERE id=?", id))
	if errors.Is(err, sql.ErrNoRows) {
		err = ErrNotFound
	}
	return u, err
}

func (s *Store) Users(ctx context.Context, after string, limit int) ([]User, error) {
	rows, err := s.db.QueryContext(ctx, "SELECT "+userCols+" FROM users WHERE id>? ORDER BY id LIMIT ?", after, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []User{}
	for rows.Next() {
		u, e := scanUser(rows)
		if e != nil {
			return nil, e
		}
		out = append(out, u)
	}
	return out, rows.Err()
}
func (s *Store) UpdateUser(ctx context.Context, id string, enabled *bool, budget *int64) (User, error) {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return User{}, err
	}
	defer tx.Rollback()
	u, err := scanUser(tx.QueryRowContext(ctx, "SELECT "+userCols+" FROM users WHERE id=?", id))
	if errors.Is(err, sql.ErrNoRows) {
		return u, ErrNotFound
	}
	if err != nil {
		return u, err
	}
	if enabled != nil {
		u.Enabled = *enabled
	}
	if budget != nil {
		u.Budget = *budget
	}
	u.BudgetUSD = FormatUSD(u.Budget)
	if _, err = tx.ExecContext(ctx, "UPDATE users SET enabled=?,budget=? WHERE id=?", u.Enabled, u.Budget, id); err != nil {
		return u, err
	}
	if err = audit(ctx, tx, "user.update", id, u); err != nil {
		return u, err
	}
	return u, tx.Commit()
}

type Principal struct{ UserID, KeyID string }

func authenticate(ctx context.Context, q interface {
	QueryRowContext(context.Context, string, ...any) *sql.Row
}, hash string, now int64) (Principal, error) {
	var p Principal
	var enabled bool
	err := q.QueryRowContext(ctx, `SELECT k.user_id,k.id,u.enabled FROM virtual_keys k JOIN users u ON u.id=k.user_id WHERE k.hash=? AND k.is_current=1 AND k.revoked=0 AND (k.expires IS NULL OR k.expires>?)`, hash, now).Scan(&p.UserID, &p.KeyID, &enabled)
	if errors.Is(err, sql.ErrNoRows) {
		return p, ErrUnauthorized
	}
	if err != nil {
		return p, err
	}
	if !enabled {
		return p, ErrDisabled
	}
	return p, nil
}
func (s *Store) Authenticate(ctx context.Context, key string) (Principal, error) {
	return authenticate(ctx, s.db, keyHash(key), time.Now().Unix())
}

type Request struct {
	ID             string          `json:"id"`
	UserID         string          `json:"user_id"`
	KeyID          string          `json:"key_id"`
	Model          string          `json:"model"`
	Provider       string          `json:"provider"`
	UpstreamModel  string          `json:"upstream_model"`
	Route          Route           `json:"-"`
	ProviderConfig Provider        `json:"-"`
	GenerationID   string          `json:"generation_id"`
	Created        int64           `json:"created_unix"`
	PeriodStart    int64           `json:"period_start_unix"`
	Lifecycle      string          `json:"lifecycle"`
	Accounting     string          `json:"accounting"`
	Cost           *int64          `json:"-"`
	CostUSD        *string         `json:"cost_usd"`
	RawCost        string          `json:"raw_cost"`
	Usage          json.RawMessage `json:"usage"`
	Attempts       int             `json:"attempts"`
	NextAttempt    int64           `json:"next_attempt_unix"`
	ErrorCode      string          `json:"error_code"`
	Finished       *int64          `json:"finished_unix"`
}

const reqCols = "id,user_id,key_id,model,provider,upstream_model,route,generation_id,created,period_start,lifecycle,accounting,cost,raw_cost,usage,attempts,next_attempt,error_code,finished,provider_config"

func scanRequest(row scanner) (Request, error) {
	var r Request
	var route, usage, provider string
	err := row.Scan(&r.ID, &r.UserID, &r.KeyID, &r.Model, &r.Provider, &r.UpstreamModel, &route, &r.GenerationID, &r.Created, &r.PeriodStart, &r.Lifecycle, &r.Accounting, &r.Cost, &r.RawCost, &usage, &r.Attempts, &r.NextAttempt, &r.ErrorCode, &r.Finished, &provider)
	if err != nil {
		return r, err
	}
	if err = json.Unmarshal([]byte(route), &r.Route); err != nil {
		return r, err
	}
	if err = json.Unmarshal([]byte(provider), &r.ProviderConfig); err != nil {
		return r, err
	}
	r.Usage = json.RawMessage(usage)
	if r.Cost != nil {
		cost := FormatUSD(*r.Cost)
		r.CostUSD = &cost
	}
	return r, nil
}

func (s *Store) Admit(ctx context.Context, secret, model string, route Route, provider Provider, now time.Time) (Request, error) {
	r := Request{ID: ID("req_"), Model: model, Provider: route.Provider, UpstreamModel: route.Model, Route: route, ProviderConfig: provider, Created: now.Unix(), Lifecycle: "admitted", Accounting: "pending"}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return r, err
	}
	defer tx.Rollback()
	p, err := authenticate(ctx, tx, keyHash(secret), now.Unix())
	if err != nil {
		return r, err
	}
	r.UserID = p.UserID
	r.KeyID = p.KeyID
	u, err := scanUser(tx.QueryRowContext(ctx, "SELECT "+userCols+" FROM users WHERE id=?", p.UserID))
	if err != nil {
		return r, err
	}
	start, end, err := Period(time.Unix(u.Anchor, 0), now, u.Cadence)
	if err != nil {
		return r, ErrNotStarted
	}
	r.PeriodStart = start.Unix()
	if _, err = tx.ExecContext(ctx, "INSERT INTO periods(user_id,start,end) VALUES(?,?,?) ON CONFLICT DO NOTHING", u.ID, start.Unix(), end.Unix()); err != nil {
		return r, err
	}
	var spent int64
	if err = tx.QueryRowContext(ctx, "SELECT spent FROM periods WHERE user_id=? AND start=?", u.ID, start.Unix()).Scan(&spent); err != nil {
		return r, err
	}
	if spent >= u.Budget {
		return r, ErrBudget
	}
	b, _ := json.Marshal(route)
	providerJSON, _ := json.Marshal(provider)
	_, err = tx.ExecContext(ctx, "INSERT INTO requests(id,user_id,key_id,model,provider,upstream_model,route,created,period_start,provider_config) VALUES(?,?,?,?,?,?,?,?,?,?)", r.ID, r.UserID, r.KeyID, model, r.Provider, r.UpstreamModel, string(b), r.Created, r.PeriodStart, string(providerJSON))
	if err != nil {
		return r, err
	}
	return r, tx.Commit()
}

func (s *Store) Generation(ctx context.Context, id, generation string) error {
	if len(generation) > 512 {
		return errors.New("generation identifier too long")
	}
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET generation_id=? WHERE id=? AND generation_id=''", generation, id)
	return err
}
func (s *Store) Finish(ctx context.Context, id, lifecycle, code string) error {
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET lifecycle=?,error_code=?,finished=?,next_attempt=? WHERE id=?", lifecycle, code, time.Now().Unix(), time.Now().Add(5*time.Second).Unix(), id)
	return err
}

func (s *Store) ObservedUsage(ctx context.Context, id string, usage json.RawMessage) error {
	if len(usage) == 0 {
		return nil
	}
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET usage=? WHERE id=? AND accounting!='settled'", string(usage), id)
	return err
}
func (s *Store) Request(ctx context.Context, id string) (Request, error) {
	r, err := scanRequest(s.db.QueryRowContext(ctx, "SELECT "+reqCols+" FROM requests WHERE id=?", id))
	if errors.Is(err, sql.ErrNoRows) {
		err = ErrNotFound
	}
	return r, err
}

// Settle atomically inserts an initial charge or appends a manual correction.
// Repeated automatic settlement is a no-op; repeated manual totals produce no delta.
func (s *Store) Settle(ctx context.Context, id string, amount int64, raw string, usage json.RawMessage, source, reason string, manual bool) error {
	if amount < 0 {
		return errors.New("negative total charge")
	}
	if len(usage) == 0 {
		usage = json.RawMessage(`{}`)
	}
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	r, err := scanRequest(tx.QueryRowContext(ctx, "SELECT "+reqCols+" FROM requests WHERE id=?", id))
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	if !manual && r.Accounting == "settled" {
		return nil
	}
	if manual && r.Finished == nil {
		return ErrConflict
	}
	old := int64(0)
	if r.Cost != nil {
		old = *r.Cost
	}
	delta := amount - old
	var spent int64
	if err = tx.QueryRowContext(ctx, "SELECT spent FROM periods WHERE user_id=? AND start=?", r.UserID, r.PeriodStart).Scan(&spent); err != nil {
		return err
	}
	if delta > 0 && spent > math.MaxInt64-delta || delta < 0 && spent < -delta {
		return errors.New("period total overflow")
	}
	if manual {
		source = "manual_adjustment"
	}
	if _, err = tx.ExecContext(ctx, "INSERT INTO ledger(request_id,amount,source,reason,created) VALUES(?,?,?,?,?)", id, delta, source, reason, time.Now().Unix()); err != nil {
		return err
	}
	if _, err = tx.ExecContext(ctx, "UPDATE periods SET spent=spent+? WHERE user_id=? AND start=?", delta, r.UserID, r.PeriodStart); err != nil {
		return err
	}
	if manual {
		usage = r.Usage
	}
	if _, err = tx.ExecContext(ctx, "UPDATE requests SET accounting='settled',cost=?,raw_cost=?,usage=? WHERE id=?", amount, raw, string(usage), id); err != nil {
		return err
	}
	if manual {
		if err = audit(ctx, tx, "request.resolve", id, map[string]any{"total_usd": FormatUSD(amount), "reason": reason}); err != nil {
			return err
		}
	}
	return tx.Commit()
}

type PeriodUsage struct {
	Start    int64  `json:"start_unix"`
	End      int64  `json:"end_unix"`
	SpentUSD string `json:"spent_usd"`
}
type Summary struct {
	User       User          `json:"user"`
	Current    *PeriodUsage  `json:"current_period"`
	Unresolved int           `json:"unresolved_requests"`
	Pending    int           `json:"pending_requests"`
	Periods    []PeriodUsage `json:"periods"`
}

func (s *Store) Summary(ctx context.Context, id string, now time.Time) (Summary, error) {
	var out Summary
	u, err := s.User(ctx, id)
	if err != nil {
		return out, err
	}
	out.User = u
	out.Periods = []PeriodUsage{}
	start, end, e := Period(time.Unix(u.Anchor, 0), now, u.Cadence)
	if e == nil {
		out.Current = &PeriodUsage{Start: start.Unix(), End: end.Unix(), SpentUSD: FormatUSD(0)}
	}
	rows, err := s.db.QueryContext(ctx, "SELECT start,end,spent FROM periods WHERE user_id=? ORDER BY start DESC LIMIT 100", id)
	if err != nil {
		return out, err
	}
	for rows.Next() {
		var p PeriodUsage
		var n int64
		if err = rows.Scan(&p.Start, &p.End, &n); err != nil {
			rows.Close()
			return out, err
		}
		p.SpentUSD = FormatUSD(n)
		out.Periods = append(out.Periods, p)
		if out.Current != nil && p.Start == out.Current.Start {
			out.Current = &p
		}
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return out, err
	}
	err = s.db.QueryRowContext(ctx, "SELECT count(*) FILTER (WHERE accounting='unresolved'),count(*) FILTER (WHERE accounting='pending') FROM requests WHERE user_id=?", id).Scan(&out.Unresolved, &out.Pending)
	return out, err
}

// History uses an opaque request ID cursor; creation time plus ID gives stable pagination.
func (s *Store) History(ctx context.Context, user, accounting, after string, limit int) ([]Request, error) {
	query := "SELECT " + reqCols + " FROM requests WHERE 1=1"
	args := []any{}
	if user != "" {
		query += " AND user_id=?"
		args = append(args, user)
	}
	if accounting != "" {
		query += " AND accounting=?"
		args = append(args, accounting)
	}
	if after != "" {
		cursor, err := s.Request(ctx, after)
		if err != nil {
			return nil, err
		}
		query += " AND (created<? OR (created=? AND id<?))"
		args = append(args, cursor.Created, cursor.Created, cursor.ID)
	}
	query += " ORDER BY created DESC,id DESC LIMIT ?"
	args = append(args, limit)
	rows, err := s.db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Request{}
	for rows.Next() {
		r, e := scanRequest(rows)
		if e != nil {
			return nil, e
		}
		out = append(out, r)
	}
	return out, rows.Err()
}

func (s *Store) Recover(ctx context.Context) error {
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET lifecycle='interrupted',finished=?,error_code='process_interrupted',next_attempt=? WHERE finished IS NULL", time.Now().Unix(), time.Now().Unix())
	return err
}

func (s *Store) RecoverStale(ctx context.Context, before int64) error {
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET lifecycle='interrupted',finished=?,error_code='finalization_interrupted',next_attempt=? WHERE finished IS NULL AND created<?", time.Now().Unix(), time.Now().Unix(), before)
	return err
}
func (s *Store) Pending(ctx context.Context, limit int) ([]Request, error) {
	rows, err := s.db.QueryContext(ctx, "SELECT "+reqCols+" FROM requests WHERE accounting='pending' AND finished IS NOT NULL AND next_attempt<=? ORDER BY next_attempt,created LIMIT ?", time.Now().Unix(), limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Request{}
	for rows.Next() {
		r, e := scanRequest(rows)
		if e != nil {
			return nil, e
		}
		out = append(out, r)
	}
	return out, rows.Err()
}
func (s *Store) Retry(ctx context.Context, r Request, max int) error {
	attempts := r.Attempts + 1
	status := "pending"
	if attempts >= max {
		status = "unresolved"
	}
	delay := time.Second * 5 * time.Duration(1<<min(attempts, 10))
	if delay > time.Hour {
		delay = time.Hour
	}
	_, err := s.db.ExecContext(ctx, "UPDATE requests SET attempts=?,next_attempt=?,accounting=? WHERE id=? AND accounting='pending'", attempts, time.Now().Add(delay).Unix(), status, r.ID)
	return err
}
func (s *Store) AccountingCounts(ctx context.Context) (pending, unresolved int, err error) {
	err = s.db.QueryRowContext(ctx, "SELECT count(*) FILTER (WHERE accounting='pending'),count(*) FILTER (WHERE accounting='unresolved') FROM requests").Scan(&pending, &unresolved)
	return
}

func (s *Store) Backup(ctx context.Context, dest string) error {
	abs, err := filepath.Abs(dest)
	if err != nil {
		return err
	}
	f, err := os.OpenFile(abs, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	// Use a separate read connection so a snapshot doesn't monopolize the
	// serialized writer connection used for admission and settlement.
	u := url.URL{Scheme: "file", Path: s.path}
	q := u.Query()
	q.Set("mode", "ro")
	u.RawQuery = q.Encode()
	reader, e := sql.Open("sqlite", u.String())
	if e != nil {
		os.Remove(abs)
		return e
	}
	defer reader.Close()
	// VACUUM INTO produces a consistent snapshot without copying a live WAL file.
	if _, err = reader.ExecContext(ctx, "VACUUM INTO ?", abs); err != nil {
		os.Remove(abs)
		return err
	}
	f, err = os.OpenFile(abs, os.O_RDWR, 0600)
	if err != nil {
		return err
	}
	defer f.Close()
	return f.Sync()
}

func VerifyBackup(ctx context.Context, path string) error {
	abs, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	u := url.URL{Scheme: "file", Path: abs}
	q := u.Query()
	q.Set("mode", "ro")
	u.RawQuery = q.Encode()
	db, err := sql.Open("sqlite", u.String())
	if err != nil {
		return err
	}
	defer db.Close()
	var result string
	if err = db.QueryRowContext(ctx, "PRAGMA integrity_check").Scan(&result); err != nil {
		return err
	}
	if result != "ok" {
		return errors.New("backup integrity check failed")
	}
	rows, err := db.QueryContext(ctx, "PRAGMA foreign_key_check")
	if err != nil {
		return err
	}
	defer rows.Close()
	if rows.Next() {
		return errors.New("backup foreign key check failed")
	}
	return rows.Err()
}
